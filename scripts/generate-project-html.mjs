import { writeFile } from 'node:fs/promises'
import path from 'node:path'
import { createServer } from 'vite'
import { marked } from 'marked'

const root = process.cwd()
const output = path.join(root, 'src/data/projectDescriptions.ts')

const render = (markdown) => marked.parse(markdown, { async: false })

const server = await createServer({
    root,
    logLevel: 'error',
    appType: 'custom',
    server: { middlewareMode: true },
})

try {
    const { projects } = await server.ssrLoadModule('/src/data/projects.ts')

    const descriptionEntries = projects
        .map(
            (project) =>
                `    ${JSON.stringify(project.id)}: ${JSON.stringify(render(project.description))},`,
        )
        .join('\n')

    const shortEntries = projects
        .filter((project) => project.shortDescription)
        .map(
            (project) =>
                `    ${JSON.stringify(project.id)}: ${JSON.stringify(render(project.shortDescription))},`,
        )
        .join('\n')

    const contents = [
        '// Generated by scripts/generate-project-html.mjs. Do not edit by hand.',
        'export const projectDescriptions: Record<string, string> = {',
        descriptionEntries,
        '}',
        '',
        'export const projectShortDescriptions: Record<string, string> = {',
        shortEntries,
        '}',
        '',
    ].join('\n')

    await writeFile(output, contents, 'utf8')
    console.log(`Wrote ${projects.length} project descriptions to ${output}`)
} finally {
    await server.close()
}
